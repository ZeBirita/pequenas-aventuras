const menuBtn = document.getElementById("menu-btn");
const navLinks = document.getElementById("nav-links");
const menuBtnIcon = menuBtn.querySelector("i");
const languageButtons = document.querySelectorAll("[data-lang]");
const supportedLanguages = ["pt-PT", "en", "es"];
const contactForm = document.getElementById("contact-form-fields");
const contactMessagePreview = document.getElementById("contact-message-preview");
const whatsappPhone = "351910512171";

function buildContactMessage(name, company, purpose, copy) {
  const template = company
    ? copy["contact.messageWithCompany"]
    : copy["contact.messageWithoutCompany"];

  return template
    .replace(/\{name\}/g, () => name)
    .replace(/\{company\}/g, () => company)
    .replace(/\{purpose\}/g, () => purpose);
}

function updateContactPreview() {
  if (!contactForm || !contactMessagePreview) {
    return;
  }

  const copy = translations[document.documentElement.lang];
  const name = contactForm.elements.name.value.trim();
  const company = contactForm.elements.company.value.trim();
  const purpose = contactForm.elements.purpose.value.trim();

  contactMessagePreview.textContent =
    name && purpose
      ? buildContactMessage(name, company, purpose, copy)
      : copy["contact.previewEmpty"];
}

function updateMenuLabel() {
  const isOpen = navLinks.classList.contains("open");
  const language = document.documentElement.lang;
  menuBtn.setAttribute(
    "aria-label",
    translations[language][isOpen ? "nav.close" : "nav.open"],
  );
  menuBtn.setAttribute("aria-expanded", String(isOpen));
}

function setLanguage(language) {
  const copy = translations[language];
  if (!copy) {
    return;
  }

  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translatedText = copy[element.dataset.i18n];
    if (translatedText !== undefined) {
      const attribute = element.dataset.i18nAttr;
      if (attribute) {
        element.setAttribute(attribute, translatedText);
      } else {
        element.textContent = translatedText;
      }
    }
  });

  document.title = document.querySelector("title").textContent;
  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
  updateContactPreview();
  updateMenuLabel();
}

menuBtn.addEventListener("click", () => {
  navLinks.classList.toggle("open");
  menuBtnIcon.setAttribute(
    "class",
    navLinks.classList.contains("open") ? "ri-close-line" : "ri-menu-line",
  );
  updateMenuLabel();
});

navLinks.addEventListener("click", (event) => {
  if (event.target.closest("a")) {
    navLinks.classList.remove("open");
    menuBtnIcon.setAttribute("class", "ri-menu-line");
    updateMenuLabel();
  }
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const language = button.dataset.lang;
    if (!supportedLanguages.includes(language)) {
      return;
    }

    setLanguage(language);
    try {
      localStorage.setItem("portfolio-language", language);
    } catch (error) {
      console.warn("Não foi possível guardar a preferência de idioma.", error);
    }
  });
});

if (contactForm) {
  contactForm.addEventListener("input", (event) => {
    event.target.setCustomValidity("");
    updateContactPreview();
  });
  contactForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const copy = translations[document.documentElement.lang];
    const name = contactForm.elements.name.value.trim();
    const company = contactForm.elements.company.value.trim();
    const purpose = contactForm.elements.purpose.value.trim();
    const invalidField = !name
      ? contactForm.elements.name
      : !purpose
        ? contactForm.elements.purpose
        : null;

    if (invalidField) {
      invalidField.setCustomValidity(copy["contact.requiredTrimmed"]);
      invalidField.reportValidity();
      return;
    }

    if (!contactForm.reportValidity()) {
      return;
    }

    const message = buildContactMessage(name, company, purpose, copy);
    if (event.submitter && event.submitter.value === "whatsapp") {
      window.location.href =
        `https://wa.me/${whatsappPhone}?text=${encodeURIComponent(message)}`;
      return;
    }

    const subject = `${copy["contact.emailSubject"]} — ${name}`;
    window.location.href =
      `${contactForm.action}?subject=${encodeURIComponent(subject)}` +
      `&body=${encodeURIComponent(message)}`;
  });
}

